# Title-Cased multi-word phrase. Excludes common stop-words and section words.
TITLE_CASE_RE = re.compile(r"\b([A-Z][a-z]+(?:[ -][A-Z][a-z0-9]+){1,4})\b")

# Phrases to ignore when looking for "constructs" — these are skill scaffolding,
# section titles, and common natural-language Title Case.
TITLE_CASE_IGNORE = {
    # Section / scaffolding
    "When To Invoke", "Known Misreadings", "Core Frameworks", "Quick Reference",
    "Reference", "References", "Source Files", "How To Apply", "Examples",
    "Reading Order", "Chapter Map", "Reference Index", "Frameworks Index",
    "Table Of Contents", "Build Workflow",
    # English Title Case noise
    "Do Not", "Must Not", "Should Not", "Buy Back",
    # Months & weekdays (rarely meaningful)
    "January", "February", "March", "April", "May", "June", "July", "August",
    "September", "October", "November", "December",
    "Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday",
}

# Verb-like leading words that almost always indicate sentence-start capitalisation
# rather than a named construct. A Title-Cased phrase starting with any of these
# is skipped by V1.
TITLE_CASE_VERB_LEADS = {
    "Add", "Apply", "Ask", "Audit", "Build", "Check", "Cite", "Compute", "Confirm",
    "Consider", "Convert", "Copy", "Create", "Decide", "Default", "Define", "Delete",
    "Describe", "Do", "Drop", "Edit", "Enable", "End", "Ensure", "Enter", "Exit",
    "Explain", "Extract", "Filter", "Find", "Fix", "Flag", "Generate", "Get",
    "Give", "Go", "Grep", "Group", "Have", "Help", "Identify", "Ignore", "Include",
    "Insert", "Install", "Invoke", "Keep", "Label", "Limit", "List", "Load", "Lock",
    "Look", "Make", "Map", "Merge", "Move", "Name", "Note", "Open", "Order", "Output",
    "Override", "Parse", "Pass", "Patch", "Pause", "Pick", "Pin", "Plan", "Plot",
    "Pop", "Post", "Prefer", "Print", "Process", "Produce", "Promote", "Propose",
    "Provide", "Pull", "Push", "Put", "Query", "Read", "Refresh", "Reject", "Remove",
    "Render", "Repeat", "Replace", "Report", "Require", "Reset", "Resolve", "Restart",
    "Return", "Reuse", "Review", "Rewrite", "Run", "Save", "Scan", "Schedule", "See",
    "Send", "Set", "Show", "Skip", "Sort", "Specify", "Split", "Start", "Stop",
    "Store", "Suggest", "Surface", "Synthesise", "Synthesize", "Take", "Tell",
    "Track", "Trigger", "Tune", "Turn", "Update", "Use", "Validate", "Verify", "View",
    "Walk", "Watch", "Write",
}

# Numeric formula patterns. We look for division / multiplication operations
# inline that look like formulas (digits with separators, optional currency).
FORMULA_RE = re.compile(
    r"(?:\$?\d[\d,]*(?:\.\d+)?\s*[÷/×*]\s*\$?\d[\d,]*(?:\.\d+)?"
    r"|\d[\d,]*\s*(?:work\s+)?hours\s*/\s*year)",
    re.IGNORECASE,
)

# List-of-N: lines with 3+ comma-or-bullet-separated items that look like
# enumeration of named entities (each starting with a capital letter).
# Heuristic: a line containing 3+ Title-Cased items separated by commas.
LISTN_RE = re.compile(
    r"(?:\*\*[A-Z][\w -]+\*\*\s*\([^)]+\)[,;]\s*){2,}"  # bold-name (gloss), ...
    r"\*\*[A-Z][\w -]+\*\*\s*\([^)]+\)"
)


def _strip_markdown(s: str) -> str:
    """Cheap normaliser for comparison: lowercase, collapse whitespace, no bold/italic."""
    s = re.sub(r"[*_`]+", "", s)
    s = re.sub(r"\s+", " ", s)
    return s.lower().strip()


def _grep_corpus(needle: str, corpus_files):
    """Return the first file containing `needle` (case-insensitive). None if absent."""
    needle_low = needle.lower()
    for f in corpus_files:
        try:
            text = f.read_text(encoding="utf-8", errors="replace").lower()
        except Exception:
            continue
        if needle_low in text:
            return f
    return None


def check_verify_claims(skill_dir: Path, fm: dict, body: str):
    """V1..V4 — fact-check SKILL.md against references/chapters/."""
    chapters_dir = skill_dir / "references" / "chapters"
    if not chapters_dir.exists():
        report("V0", WARN, "verify-claims: chapters/ absent",
               "Skipping fact-verification (no references/chapters/ to grep against)")
        return
    corpus = sorted(chapters_dir.glob("*.md"))
    if not corpus:
        report("V0", WARN, "verify-claims: chapters/ empty", "No chapter files found")
        return

    # V1 — Title-Cased constructs in SKILL.md must appear verbatim in some chapter.
    constructs_found = set(TITLE_CASE_RE.findall(body))
    if fm and fm.get("description"):
        constructs_found |= set(TITLE_CASE_RE.findall(fm["description"]))
    misses = []
    for c in sorted(constructs_found):
        if c in TITLE_CASE_IGNORE:
            continue
        # Skip phrases starting with a verb — these are almost always
        # sentence-start capitalisation, not constructs.
        if c.split()[0] in TITLE_CASE_VERB_LEADS:
            continue
        if _grep_corpus(c, corpus) is None:
            misses.append(c)
    if misses:
        report("V1", FAIL, "constructs verbatim in source",
               f"{len(misses)} Title-Cased phrase(s) not found in any chapter "
               f"(possible hallucination or working name needing *(working name)* flag): "
               f"{misses[:8]}{'...' if len(misses) > 8 else ''}")
    else:
        report("V1", PASS, "constructs verbatim in source",
               f"all {len(constructs_found)} Title-Cased phrases grep-verified")

    # V2 — numeric formulas in SKILL.md must appear in some chapter.
    formulas = list(set(FORMULA_RE.findall(body)))
    formula_misses = []
    for f_str in formulas:
        # Normalise: remove spaces around operators
        canon = re.sub(r"\s+", "", f_str)
        # Allow either ÷ or / to match — book may use the other glyph
        canon_variants = {canon,
                          canon.replace("÷", "/"),
                          canon.replace("/", "÷"),
                          canon.replace("×", "*"),
                          canon.replace("*", "×")}
        if not any(_grep_corpus(v, corpus) or _grep_corpus(re.sub(r",", "", v), corpus)
                   for v in canon_variants):
            formula_misses.append(f_str)
    if formulas:
        if formula_misses:
            report("V2", FAIL, "formulas verbatim in source",
                   f"{len(formula_misses)} formula(s) not found in any chapter: "
                   f"{formula_misses}")
        else:
            report("V2", PASS, "formulas verbatim in source",
                   f"all {len(formulas)} numeric formula(s) verified")
    else:
        report("V2", INFO, "formulas verbatim in source", "no formulas detected in SKILL.md")

    # V3 — Bold-Name (gloss-text), ... lists-of-N (e.g. Time Assassins)
    listn_matches = LISTN_RE.findall(body)
    if listn_matches:
        member_misses = []
        for listn in listn_matches:
            # Extract bold names
            names = re.findall(r"\*\*([A-Z][\w -]+)\*\*", listn)
            for n in names:
                if _grep_corpus(n, corpus) is None:
                    member_misses.append(n)
        if member_misses:
            report("V3", FAIL, "list members verbatim in source",
                   f"{len(member_misses)} list member(s) not found in any chapter: "
                   f"{member_misses[:8]}")
        else:
            report("V3", PASS, "list members verbatim in source",
                   f"all members of {len(listn_matches)} enumerated list(s) verified")
    else:
        report("V3", INFO, "list members verbatim in source",
               "no bold enumerated lists detected in SKILL.md")

    # V4 — Cross-file consistency: same Title-Cased construct, same wording.
    # Compare SKILL.md against references/index.md and references/frameworks/index.md
    # (the two highest-risk derivative files for re-hallucination).
    deriv_files = [
        skill_dir / "references" / "index.md",
        skill_dir / "references" / "frameworks" / "index.md",
        skill_dir / "references" / "glossary.md",
    ]
    deriv_files = [f for f in deriv_files if f.exists()]
    cross_misses = []
    for f in deriv_files:
        try:
            d_text = f.read_text(encoding="utf-8")
        except Exception:
            continue
        # For each Title-Cased construct that DOES appear in both SKILL.md and
        # this derivative, check that the gloss/context phrase isn't contradicted.
        # Cheap heuristic: extract every Title-Cased phrase from the derivative
        # and ensure each one also appears verbatim in the corpus.
        deriv_constructs = set(TITLE_CASE_RE.findall(d_text)) - TITLE_CASE_IGNORE
        for c in deriv_constructs:
            if c.split()[0] in TITLE_CASE_VERB_LEADS:
                continue
            if _grep_corpus(c, corpus) is None:
                cross_misses.append(f"{f.relative_to(skill_dir)}: '{c}'")
    if cross_misses:
        report("V4", FAIL, "derivative-file constructs verbatim",
               f"{len(cross_misses)} construct(s) in derivative refs not found in chapters "
               f"(re-hallucination risk): {cross_misses[:8]}")
    elif deriv_files:
        report("V4", PASS, "derivative-file constructs verbatim",
               f"checked {len(deriv_files)} derivative file(s)")
    else:
        report("V4", INFO, "derivative-file constructs verbatim",
               "no derivative index/glossary files to check")


def main():
    verify_claims = False
    positional = []
    for arg in sys.argv[1:]:
        if arg == "--verify-claims":
            verify_claims = True
        elif arg.startswith("-"):
            print(f"ERROR: unknown flag {arg}", file=sys.stderr)
            sys.exit(2)
        else:
            positional.append(arg)
    if len(positional) != 1:
        print("Usage: audit_skill.py <skill-dir> [--verify-claims]", file=sys.stderr)
        sys.exit(2)
    skill_dir = Path(positional[0]).expanduser().resolve()
    if not skill_dir.is_dir():
        print(f"ERROR: {skill_dir} is not a directory", file=sys.stderr)
        sys.exit(2)
    skill_md = skill_dir / "SKILL.md"
    if not skill_md.exists():
        print(f"ERROR: {skill_md} not found", file=sys.stderr)
        sys.exit(2)

    content = skill_md.read_text(encoding="utf-8")
    fm, body = parse_frontmatter(content)

    check_frontmatter(fm)
    check_body(body)
    check_content(body)
    check_references(skill_dir, body)
    check_structural(skill_dir, body)
    check_book_specific(skill_dir)
    if fm and fm.get("description"):
        check_named_construct_count(fm["description"])
    if verify_claims:
        check_verify_claims(skill_dir, fm or {}, body)

    # Render
    print(f"\nAudit: {skill_dir}\n" + "=" * 60)
    counts = {PASS: 0, WARN: 0, FAIL: 0, INFO: 0}
    for cid, sev, name, detail in results:
        counts[sev] += 1
        marker = {PASS: "✓", WARN: "!", FAIL: "✗", INFO: "·"}[sev]
        line = f"  [{marker}] {sev:4s}  {cid:4s} {name}"
        if detail:
            line += f"  — {detail}"
        print(line)
    print("=" * 60)
    print(f"  {counts[PASS]} PASS  ·  {counts[WARN]} WARN  ·  "
          f"{counts[FAIL]} FAIL  ·  {counts[INFO]} INFO")
    sys.exit(1 if counts[FAIL] else 0)


