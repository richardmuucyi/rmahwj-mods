#!/usr/bin/env python3
"""Audit a Claude Code skill against Anthropic's best practices.

Usage:
    python3 audit_skill.py <skill-dir> [--verify-claims]

Modes:
    default          Mechanical structural checks (frontmatter, line counts,
                     link integrity, voice patterns, generic boilerplate).
    --verify-claims  Additionally fact-check SKILL.md against
                     references/chapters/*.md — every numeric, list-of-N, and
                     Title-Cased construct in SKILL.md must appear verbatim
                     in at least one chapter file. Catches the three
                     hallucination categories from the buy-back-your-time v1
                     review (wrong formula, fabricated list members,
                     fabricated framework membership) plus derivative-file
                     re-hallucination (SKILL.md vs references/index.md).
                     Requires references/chapters/ to exist; otherwise warns
                     and runs mechanical checks only.

Exit code:
    0 if all FAIL-severity checks pass (WARN/INFO findings are allowed).
    1 if any FAIL-severity check fails.

Output:
    Human-readable checklist with PASS / FAIL / WARN / INFO per check.

Source rationale: references/audit-checklist.md (in this skill's folder)
"""
import os
import re
import sys
from pathlib import Path
from typing import Optional

FAIL = "FAIL"
WARN = "WARN"
INFO = "INFO"
PASS = "PASS"

RESERVED_NAMES = {"anthropic", "claude"}
FIRST_PERSON_PATTERNS = [
    r"\bI can\b", r"\bI will\b", r"\bI help\b",
    r"\byou can use this\b", r"\bthis lets you\b",
]
GENERIC_BOILERPLATE = [
    "Look up API references",
    "Find code examples and implementation patterns",
    "complete documentation structure",
    "Generated by Skill Seeker",
    "Understand surrounded-by-idiots concepts",  # placeholder text
]
PRACTITIONER_VOICE_RED_FLAGS = [
    r"\bThe book teaches\b", r"\bThe author argues\b",
    r"\bThe text explains\b", r"\bThis book covers\b",
]

results = []


def report(check_id: str, severity: str, name: str, detail: str = ""):
    results.append((check_id, severity, name, detail))


def parse_frontmatter(content: str) -> tuple[Optional[dict], str]:
    """Return (frontmatter_dict, body) or (None, content) if no frontmatter."""
    if not content.startswith("---\n"):
        return None, content
    end = content.find("\n---\n", 4)
    if end == -1:
        return None, content
    fm_text = content[4:end]
    body = content[end + 5:]
    fm = {}
    # Simple key: value parser — supports multi-line values
    current_key = None
    for line in fm_text.split("\n"):
        m = re.match(r"^([a-zA-Z_-]+):\s*(.*)$", line)
        if m:
            current_key = m.group(1)
            fm[current_key] = m.group(2).strip()
        elif current_key and line.startswith(" "):
            fm[current_key] += " " + line.strip()
    return fm, body


def check_frontmatter(fm: Optional[dict]):
    if fm is None:
        report("F1", FAIL, "Frontmatter exists",
               "SKILL.md must start with --- frontmatter ---")
        return
    # F1
    name = fm.get("name", "").strip()
    if not name:
        report("F1", FAIL, "name exists", "Empty or missing")
    else:
        report("F1", PASS, "name exists", name)
    # F2
    if name:
        if not re.fullmatch(r"[a-z0-9-]+", name):
            report("F2", FAIL, "name format",
                   f"Must be lowercase letters/numbers/hyphens only: '{name}'")
        elif len(name) > 64:
            report("F2", FAIL, "name length", f"{len(name)} > 64 chars")
        else:
            report("F2", PASS, "name format", f"{len(name)} chars")
    # F3
    if name and any(w in name.lower() for w in RESERVED_NAMES):
        report("F3", FAIL, "name reserved-word", f"contains reserved word: '{name}'")
    elif name:
        report("F3", PASS, "name reserved-word")
    # F4
    desc = fm.get("description", "").strip()
    if not desc:
        report("F4", FAIL, "description exists", "Empty or missing")
    else:
        report("F4", PASS, "description exists", f"{len(desc)} chars")
    # F5
    if desc:
        if len(desc) > 1024:
            report("F5", FAIL, "description length", f"{len(desc)} > 1024 chars")
        else:
            report("F5", PASS, "description length", f"{len(desc)} chars")
    # F6 — first-person check
    if desc:
        hits = [p for p in FIRST_PERSON_PATTERNS if re.search(p, desc, re.IGNORECASE)]
        if hits:
            report("F6", FAIL, "description third-person",
                   f"Found first-person phrase(s): {hits}")
        else:
            report("F6", PASS, "description third-person")
    # F7 — WHEN clause
    if desc:
        if re.search(r"\b[Uu]se when\b|\b[Tt]rigger\b|\b[Ww]hen the user\b", desc):
            report("F7", PASS, "description WHEN clause")
        else:
            report("F7", WARN, "description WHEN clause",
                   "No 'Use when' phrasing — discoverability suffers")
    # F8
    if name and re.search(r"<[a-zA-Z]", name):
        report("F8", FAIL, "no XML in name")
    elif desc and re.search(r"<[a-zA-Z]", desc):
        report("F8", FAIL, "no XML in description")
    else:
        report("F8", PASS, "no XML in frontmatter")


def check_body(body: str):
    lines = body.split("\n")
    n_lines = len(lines)
    # B1
    if n_lines > 500:
        report("B1", FAIL, "body ≤500 lines", f"{n_lines} lines")
    else:
        report("B1", PASS, "body ≤500 lines", f"{n_lines} lines")
    # B2
    if n_lines > 200:
        report("B2", WARN, "body ≤200 lines (target)", f"{n_lines} lines")
    else:
        report("B2", PASS, "body ≤200 lines (target)")
    # B3 — H1
    first_content = next((l for l in lines if l.strip()), "")
    if first_content.startswith("# "):
        report("B3", PASS, "has H1", first_content[:60])
    else:
        report("B3", WARN, "has H1", f"First content line: '{first_content[:60]}'")
    # B4 — "When to invoke" or equivalent
    if re.search(r"^##\s+(When to invoke|When to use|Triggers|Use when)",
                 body, re.MULTILINE | re.IGNORECASE):
        report("B4", PASS, "has When-to-invoke section")
    else:
        report("B4", WARN, "has When-to-invoke section",
               "Add a section enumerating triggers")
    # B5 — reference section
    if re.search(r"^##\s+(Reference|References)\b", body, re.MULTILINE | re.IGNORECASE):
        report("B5", PASS, "has Reference section")
    else:
        report("B5", WARN, "has Reference section",
               "Add a section listing references/ files")
    # B6 — time-sensitive content
    time_hits = re.findall(
        r"\b(?:as of|before|after)\s+(?:Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)\w*\s+\d{4}",
        body, re.IGNORECASE,
    )
    if time_hits:
        report("B6", WARN, "no time-sensitive content", f"Found: {time_hits[:3]}")
    else:
        report("B6", PASS, "no time-sensitive content")


def check_content(body: str):
    # C1 — practitioner voice
    voice_hits = []
    for p in PRACTITIONER_VOICE_RED_FLAGS:
        voice_hits.extend(re.findall(p, body, re.IGNORECASE))
    if voice_hits:
        report("C1", WARN, "practitioner voice",
               f"Found expository phrases: {voice_hits[:3]}")
    else:
        report("C1", PASS, "practitioner voice")
    # C4 — boilerplate
    boiler_hits = [b for b in GENERIC_BOILERPLATE if b in body]
    if boiler_hits:
        report("C4", FAIL, "no generic boilerplate", f"Found: {boiler_hits}")
    else:
        report("C4", PASS, "no generic boilerplate")
    # C3 — anti-scope section
    if re.search(r"^##\s+(What this skill is\s+\*?not|Anti-scope|Limitations)",
                 body, re.MULTILINE | re.IGNORECASE):
        report("C3", PASS, "has anti-scope section")
    else:
        report("C3", WARN, "has anti-scope section",
               "Add 'What this skill is not' section")


def check_references(skill_dir: Path, skill_md_body: str):
    # R1 — all linked files exist
    links = re.findall(r"\]\(([^)]+\.md|[^)]+/)\)", skill_md_body)
    missing = []
    for link in links:
        if link.startswith(("http://", "https://")):
            continue
        target = skill_dir / link.split("#")[0].rstrip("/")
        # Allow directory links (chapters/)
        if not target.exists() and not (skill_dir / link.split("#")[0]).exists():
            missing.append(link)
    if missing:
        report("R1", FAIL, "all SKILL.md links resolve", f"Missing: {missing}")
    else:
        report("R1", PASS, "all SKILL.md links resolve")

    # R2 — one-level depth: reference files shouldn't link to other reference files
    ref_dir = skill_dir / "references"
    if ref_dir.exists():
        violations = []
        for md_file in ref_dir.rglob("*.md"):
            try:
                content = md_file.read_text(encoding="utf-8")
            except Exception:
                continue
            # Look for links to other files in references/ (except sibling index/glossary
            # which are allowed as cross-pointers, and chapter-internal links are fine)
            nested = re.findall(r"\]\((?:\.\./)?references/([^)]+\.md)\)", content)
            for n in nested:
                # Allowed: cross-links between index/glossary/chapters at same level
                violations.append(f"{md_file.relative_to(skill_dir)} -> references/{n}")
        if violations and len(violations) > 5:
            report("R2", WARN, "one-level reference depth",
                   f"{len(violations)} cross-refs (chapter↔index OK; too many is a smell)")
        else:
            report("R2", PASS, "one-level reference depth")

    # R3 — TOC on long references (excludes references/chapters/* — those are leaf source files)
    if ref_dir.exists():
        toc_missing = []
        for md_file in ref_dir.rglob("*.md"):
            # Skip per-chapter source files — they're leaves, not navigation surfaces
            if "chapters" in md_file.relative_to(ref_dir).parts:
                continue
            try:
                lines = md_file.read_text(encoding="utf-8").split("\n")
            except Exception:
                continue
            if len(lines) > 100:
                first_25 = "\n".join(lines[:25])
                if "## Contents" not in first_25 and "## Table of contents" not in first_25.lower():
                    toc_missing.append(str(md_file.relative_to(skill_dir)))
        if toc_missing:
            report("R3", WARN, "TOC on long references",
                   f"Files >100 lines without TOC: {toc_missing}")
        else:
            report("R3", PASS, "TOC on long references")


def check_structural(skill_dir: Path, skill_md_body: str):
    # S1 — forward slashes
    backslash_hits = re.findall(r"\]\([^)]*\\[^)]*\)", skill_md_body)
    if backslash_hits:
        report("S1", FAIL, "forward slashes only",
               f"Found backslash path(s): {backslash_hits[:3]}")
    else:
        report("S1", PASS, "forward slashes only")
    # S2 — no monolith
    monolith = skill_dir / "references" / "book.md"
    if monolith.exists():
        size = monolith.stat().st_size
        if size > 50_000:
            report("S2", FAIL, "no book.md monolith",
                   f"references/book.md is {size} bytes — split into chapters/")
        else:
            report("S2", WARN, "no book.md monolith",
                   f"references/book.md exists ({size}B); consider splitting")
    else:
        report("S2", PASS, "no book.md monolith")
    # S4 — empty dirs
    empty_dirs = []
    for sub in ["scripts", "assets", "references/chapters"]:
        d = skill_dir / sub
        if d.exists() and d.is_dir() and not any(d.iterdir()):
            empty_dirs.append(sub)
    if empty_dirs:
        report("S4", INFO, "no empty directories", f"Empty: {empty_dirs}")
    else:
        report("S4", PASS, "no empty directories")


def check_book_specific(skill_dir: Path):
    chapters_dir = skill_dir / "references" / "chapters"
    if not chapters_dir.exists():
        report("K1", INFO, "(skipped — not a book skill)")
        return
    # K1 — chapter file count
    chapter_files = list(chapters_dir.glob("*.md"))
    if len(chapter_files) < 5:
        report("K1", WARN, "chapter file count ≥5", f"Found {len(chapter_files)}")
    else:
        report("K1", PASS, "chapter file count ≥5", f"{len(chapter_files)} chapters")
    # K2 — glossary
    if (skill_dir / "references" / "glossary.md").exists():
        report("K2", PASS, "glossary.md present")
    else:
        report("K2", WARN, "glossary.md present", "Recommended for book skills")
    # K3 — index
    if (skill_dir / "references" / "index.md").exists():
        report("K3", PASS, "index.md present")
    else:
        report("K3", FAIL, "index.md present", "Required for navigation")
    # K4 — evals
    if (skill_dir / "references" / "_evals.md").exists():
        report("K4", PASS, "_evals.md present")
    else:
        report("K4", WARN, "_evals.md present", "Recommended — 3 test scenarios")
    # R4 — chapter H1s
    bad_h1 = []
    for f in chapter_files:
        try:
            first = f.read_text(encoding="utf-8").split("\n", 1)[0]
        except Exception:
            continue
        if not first.startswith("# ") or len(first) < 5 or re.fullmatch(r"# \d+", first.strip()):
            bad_h1.append(f.name)
    if bad_h1:
        report("R4", WARN, "chapter files have meaningful H1",
               f"Bare/missing H1: {bad_h1[:5]}")
    else:
        report("R4", PASS, "chapter files have meaningful H1")


def check_named_construct_count(desc: str):
    # C2 — at least 3 named constructs in description
    # Heuristic: count Title-Cased proper-noun-like phrases inside parens
    constructs = re.findall(r"\(([^)]+)\)", desc)
    construct_text = " ".join(constructs) if constructs else desc
    title_cased = re.findall(r"\b[A-Z][a-z]+(?:\s+[A-Z][a-z]+){1,3}\b", construct_text)
    n = len(set(title_cased))
    if n < 3:
        report("C2", INFO, "named constructs in description",
               f"~{n} detected (heuristic); confirm description names the book's key terms")
    else:
        report("C2", PASS, "named constructs in description", f"~{n} detected")


